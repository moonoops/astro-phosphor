export function getShopOptionCost(
  shopId: ShopId,
  optionId: string,
  shopPurchases: Partial<Record<ShopId, number>> = {},
): number {
  const shop = SHOPS[shopId];
  const opt = shop?.options.find((item) => item.id === optionId);
  if (!opt) return 0;
  const bought = Math.max(0, Math.floor(shopPurchases[shopId] ?? 0));
  return opt.cost + (opt.costStep ? bought * opt.costStep : 0);
}

export function formatShopCostText(
  shopId: ShopId,
  optionId: string,
  shopPurchases: Partial<Record<ShopId, number>> = {},
): string {
  const shop = SHOPS[shopId];
  const opt = shop?.options.find((item) => item.id === optionId);
  if (!opt) return '';
  const currentCost = getShopOptionCost(shopId, optionId, shopPurchases);
  switch (opt.currency) {
    case 'gold':
      return `${currentCost} 金币`;
    case 'exp':
      return `${currentCost} 经验`;
    case 'yellowKey':
      return `${currentCost} [Y]`;
    case 'blueKey':
      return `${currentCost} [B]`;
    case 'redKey':
      return `${currentCost} [R]`;
  }
}
