const HARD_MONSTER_CACHE = new Map<string, MonsterDef>();

export function getMonsterDef(id: string, difficulty: Difficulty = 'standard'): MonsterDef | undefined {
  const base = MONSTERS[id];
  if (!base || difficulty === 'standard' || id === 'greenSlime') return base;
  const cached = HARD_MONSTER_CACHE.get(id);
  if (cached) return cached;

  const hpMul = base.tier === 1 ? 1.06 : base.tier === 2 ? 1.07 : 1.08;
  const statMul = base.tier === 1 ? 1.03 : base.tier === 2 ? 1.035 : base.tier === 3 ? 1.04 : 1.03;
  const extraSpecial: MonsterSpecial[] = base.special ? [...base.special] : [];
  if ((id === 'redDemonKing' || id === 'ghostLord' || id === 'finalBoss') && !extraSpecial.includes('firstStrike')) {
    extraSpecial.push('firstStrike');
  }
  const scaled: MonsterDef = {
    ...base,
    hp: Math.round(base.hp * hpMul),
    atk: Math.round(base.atk * statMul),
    def: Math.round(base.def * statMul),
    special: extraSpecial.length ? extraSpecial : undefined,
  };
  HARD_MONSTER_CACHE.set(id, scaled);
  return scaled;
}

